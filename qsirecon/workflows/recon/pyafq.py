# Spec keys that QSIRecon reads itself. They are not ParticipantAFQ arguments.
QSIRECON_ONLY_PARAMS = {'use_external_tracking'}
NON_TOP_LEVEL_SECTIONS = {
    'AFQ_desc',
    'BIDS_PARAMS',
    'TRACTOGRAPHY_PARAMS',
    'SEGMENTATION_PARAMS',
}


def _parse_qsirecon_params_dict(params_dict):
    """Sort a flat recon spec parameter dict into ParticipantAFQ kwargs.

    Unknown keys raise an error, so a parameter removed from pyAFQ fails when
    the workflow is built instead of being silently ignored.
    """
    arg_dict = afb.func_dict_to_arg_dict()
    tracking_args = set(arg_dict['TRACTOGRAPHY_PARAMS'])
    segmentation_args = set(arg_dict['SEGMENTATION_PARAMS'])
    cleaning_args = set(inspect.signature(clean_bundle).parameters) - {'tg', 'return_idx'}
    top_level_args = {'export'}
    for section, args in arg_dict.items():
        if section not in NON_TOP_LEVEL_SECTIONS:
            top_level_args.update(args)

    kwargs, tracking, segmentation, cleaning = {}, {}, {}, {}
    unknown = []
    for key, raw_value in params_dict.items():
        if key in QSIRECON_ONLY_PARAMS:
            continue
        if key in tracking_args:
            target = tracking
        elif key in segmentation_args:
            target = segmentation
        elif key in cleaning_args:
            target = cleaning
        elif key in top_level_args:
            target = kwargs
        else:
            unknown.append(key)
            continue
        # pyafq_str_to_val raises IndexError on an empty string
        value = None if raw_value == '' else afb.pyafq_str_to_val(raw_value)
        if value is not None:
            target[key] = value

    if unknown:
        raise ValueError(f'Unknown pyAFQ parameters in recon spec: {sorted(unknown)}')

    if cleaning:
        segmentation['cleaning_params'] = cleaning
    if tracking:
        kwargs['tracking_params'] = tracking
    if segmentation:
        kwargs['segmentation_params'] = segmentation
    return kwargs


def init_pyafq_wf(inputs_dict, name='afq', qsirecon_suffix='', params={}):
    """Run PyAFQ on some qsirecon outputs

    Inputs

        *qsirecon outputs*

    Outputs
        profiles_csv
            CSV file containing the tract profiles generated by pyAFQ.

    """
    if not inputs_dict.get('has_qsiprep_t1w'):
        raise ValueError('pyAFQ requires a T1w image, but none was found for this subject.')

    workflow = pe.Workflow(name=name)
    suffix_str = f' (outputs written to qsirecon-{qsirecon_suffix})' if qsirecon_suffix else ''
    workflow.__desc__ = (
        f'\n\n#### PyAFQ{suffix_str}\n\n'
        f'PyAFQ run on version {AFQ.__version__} with the following configuration: '
    )

    inputnode = pe.Node(
        niu.IdentityInterface(fields=recon_workflow_input_fields + ['tck_file']), name='inputnode'
    )
    outputnode = pe.Node(
        niu.IdentityInterface(fields=['afq_dir', 'recon_scalars']), name='outputnode'
    )
    outputnode.inputs.recon_scalars = []
    omp_nthreads = config.nipype.omp_nthreads
    kwargs = _parse_qsirecon_params_dict(params)

    workflow.__desc__ += f'{kwargs!s}.'

    run_afq = pe.Node(
        PyAFQRecon(kwargs=kwargs, n_procs=omp_nthreads), name='run_afq', n_procs=omp_nthreads
    )

    if params.get('use_external_tracking', False):
        workflow.connect([(inputnode, run_afq, [('tck_file', 'tck_file')])])

    workflow.connect([
        (inputnode, run_afq, [
            ('dwi_file', 'dwi_file'),
            ('bval_file', 'bval_file'),
            ('bvec_file', 'bvec_file'),
            ('acpc_preproc', 't1_file'),
            ('acpc_brain_mask', 'mask_file'),
            ('acpc_csf_probseg', 'csf_probseg'),
            ('acpc_gm_probseg', 'gm_probseg'),
            ('acpc_wm_probseg', 'wm_probseg'),
            ('template_to_acpc_xfm', 'itk_file'),
        ]),
        (run_afq, outputnode, [('afq_dir', 'afq_dir')]),
    ])  # fmt:skip

    if qsirecon_suffix:
        # Save the output in the outputs directory
        ds_afq = pe.Node(
            ReconDerivativesDataSink(
                qsirecon_suffix=qsirecon_suffix,
                extension='.nii.gz',
                use_ext=False,
                dismiss_entities=['desc'],
            ),
            name='ds_' + name,
            run_without_submitting=True,
        )
        workflow.connect(run_afq, 'afq_dir', ds_afq, 'in_file')

    return clean_datasinks(workflow, qsirecon_suffix)
