# Recon spec parameters that QSIRecon consumes itself rather than forwarding to pyAFQ.
QSIRECON_ONLY_PARAMS = frozenset({'export', 'use_external_tracking'})


def _parse_qsirecon_params_dict(params_dict):
    """Convert the flat parameters of a recon spec node into ParticipantAFQ keyword arguments.

    Top-level parameters are matched against the argument dictionary of the installed pyAFQ.
    The keyword arguments of pyAFQ's tractography, bundle recognition and bundle cleaning
    functions are nested the way ParticipantAFQ expects them (cleaning parameters go inside
    the segmentation parameters, because recognize() passes them on to clean_bundle()).
    Parameters pyAFQ does not recognize are dropped with a warning, because they would
    otherwise silently take no effect.
    """
    kwargs = {}
    known_args = set()

    # pyAFQ's own argument dictionary lists the keyword arguments of its tasks. Its *_PARAMS
    # sections come from GroupAFQ and the functions handled below, and include positional
    # arguments that pyAFQ fills in itself, so they are skipped here.
    arg_dict = afb.func_dict_to_arg_dict()
    for section, args in arg_dict.items():
        if section == 'AFQ_desc' or section.endswith('_PARAMS'):
            continue

        for arg in args:
            known_args.add(arg)
            if arg in params_dict:
                kwargs[arg] = afb.pyafq_str_to_val(params_dict[arg])

    nested_params = {
        ('tracking_params',): get_default_args(aft.track),
        ('segmentation_params',): get_default_args(recognize),
        ('segmentation_params', 'cleaning_params'): get_default_args(clean_bundle),
    }
    for path, defaults in nested_params.items():
        for arg in defaults:
            known_args.add(arg)
            if arg not in params_dict:
                continue

            target = kwargs
            for key in path:
                target = target.setdefault(key, {})

            target[arg] = afb.pyafq_str_to_val(params_dict[arg])

    unrecognized = sorted(
        set(params_dict) - known_args - set(afb.qsi_prep_ignore_params) - QSIRECON_ONLY_PARAMS
    )
    if unrecognized:
        config.loggers.workflow.warning(
            'The following pyAFQ parameters are not recognized by pyAFQ %s and will be '
            'ignored: %s. They were most likely renamed or removed upstream; check the pyAFQ '
            'documentation and update the recon spec.',
            AFQ.__version__,
            ', '.join(unrecognized),
        )

    return kwargs


def init_pyafq_wf(inputs_dict, name='afq', qsirecon_suffix='', params={}):
    """Run PyAFQ on some qsirecon outputs

    Inputs

        *qsirecon outputs*

    Outputs
        profiles_csv
            CSV file containing the tract profiles generated by pyAFQ.

    """
    if not inputs_dict.get('has_qsiprep_t1w', False):
        raise ValueError(
            'pyAFQ requires a T1w image, brain mask and tissue probability maps aligned with '
            'the DWI data, but no high-resolution anatomical data were found in the '
            'preprocessed inputs.'
        )

    workflow = pe.Workflow(name=name)
    suffix_str = f' (outputs written to qsirecon-{qsirecon_suffix})' if qsirecon_suffix else ''
    workflow.__desc__ = (
        f'\n\n#### PyAFQ{suffix_str}\n\n'
        f'PyAFQ run on version {AFQ.__version__} with the following configuration: '
    )

    inputnode = pe.Node(
        niu.IdentityInterface(fields=recon_workflow_input_fields + ['tck_file']), name='inputnode'
    )
    outputnode = pe.Node(
        niu.IdentityInterface(fields=['afq_dir', 'recon_scalars']), name='outputnode'
    )
    outputnode.inputs.recon_scalars = []
    omp_nthreads = config.nipype.omp_nthreads
    kwargs = _parse_qsirecon_params_dict(params)

    workflow.__desc__ += f'{kwargs!s}.'

    run_afq = pe.Node(
        PyAFQRecon(
            kwargs=kwargs,
            n_procs=omp_nthreads,
            export=params.get('export', 'all'),
        ),
        name='run_afq',
        n_procs=omp_nthreads,
    )

    if params.get('use_external_tracking', False):
        workflow.connect([(inputnode, run_afq, [('tck_file', 'tck_file')])])

    workflow.connect([
        (inputnode, run_afq, [
            ('dwi_file', 'dwi_file'),
            ('bval_file', 'bval_file'),
            ('bvec_file', 'bvec_file'),
            # pyAFQ needs anatomical images registered to (not resampled onto) the DWI.
            # These specs run in T1w space, so the QSIPrep anatomical outputs qualify.
            ('acpc_preproc', 't1_file'),
            ('acpc_brain_mask', 'mask_file'),
            ('acpc_csf_probseg', 'csf_probseg'),
            ('acpc_gm_probseg', 'gm_probseg'),
            ('acpc_wm_probseg', 'wm_probseg'),
            ('template_to_acpc_xfm', 'itk_file'),
        ]),
        (run_afq, outputnode, [('afq_dir', 'afq_dir')]),
    ])  # fmt:skip

    if qsirecon_suffix:
        # Save the output in the outputs directory
        ds_afq = pe.Node(
            ReconDerivativesDataSink(
                qsirecon_suffix=qsirecon_suffix,
                extension='.nii.gz',
                use_ext=False,
                dismiss_entities=['desc'],
            ),
            name='ds_' + name,
            run_without_submitting=True,
        )
        workflow.connect(run_afq, 'afq_dir', ds_afq, 'in_file')

    return clean_datasinks(workflow, qsirecon_suffix)
